#!/usr/bin/env python3
"""Gzips firmware/web/index.html into firmware/eload/webpage.h (PROGMEM array)."""
import gzip, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'web', 'index.html'); dst = os.path.join(here, '..', 'eload', 'webpage.h')
data = gzip.compress(open(src, 'rb').read(), compresslevel=9, mtime=0)
rows = [', '.join('0x%02x' % b for b in data[i:i + 20]) for i in range(0, len(data), 20)]
open(dst, 'w').write('// Generated by tools/embed_web.py from web/index.html - do not edit\n#pragma once\n#include <Arduino.h>\n'
                     '#define INDEX_HTML_GZ_LEN %d\nstatic const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n  %s\n};\n' % (len(data), ',\n  '.join(rows)))
print('webpage.h: %d bytes gzip (%d raw)' % (len(data), os.path.getsize(src)))
